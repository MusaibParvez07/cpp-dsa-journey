// Relational or Comparison Operators
#include <iostream>
using namespace std;

int main()
{
    int a = 10, b = 5;
    cout << "a==b is: " << (a == b) << endl; /*It will return 0 which means false.*/
    cout << "a>b is: " << (a > b) << endl;   /*It will return 1 which means true.*/
    cout << "a>=b is: " << (a >= b) << endl; /*It will return 1 which means true.*/
    cout << "a<b is: " << (a < b) << endl;   /*It will return 0 which means false.*/
    cout << "a<=b is: " << (a <= b) << endl; /*It will return 0 which means false.*/
    cout << "a!=b is: " << (a != b) << endl; /*It will return 1 which means true.*/
}